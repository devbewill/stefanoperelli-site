import fs from 'fs';
import path from 'path';

const files = [
  'src/components/App.astro',
  'src/components/Footer.astro',
  'src/components/ExperienceItem.astro',
  'src/pages/about.astro',
  'src/pages/resume.astro',
  'src/pages/blog/index.astro',
  'src/pages/experiments/index.astro',
  'src/layouts/BlogPost.astro'
];

for (const file of files) {
  const filePath = path.resolve(process.cwd(), file);
  if (fs.existsSync(filePath)) {
    let content = fs.readFileSync(filePath, 'utf-8');
    // regex to remove `uppercase ` or ` uppercase` from class strings
    content = content.replace(/\buppercase\b/g, '');
    // clean up any double spaces generated by the removal
    content = content.replace(/  +/g, ' ');
    fs.writeFileSync(filePath, content, 'utf-8');
    console.log(`Removed uppercase from ${file}`);
  } else {
    console.warn(`File not found: ${filePath}`);
  }
}
